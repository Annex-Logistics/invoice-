export type Currency = {
  code: string;      // e.g. "USD"
  symbol: string;    // e.g. "$"
  name: string;      // e.g. "US Dollar"
};

export type LineItem = {
  id: string;
  description: string;
  quantity: number;
  rate: number;
};

export type Party = {
  name: string;
  email: string;
  address: string;
  phone: string;
};

export type DocumentKind = "invoice" | "estimate" | "receipt" | "delivery-note";

export type InvoiceStatus = "draft" | "sent" | "paid" | "overdue";
export type EstimateStatus = "draft" | "sent" | "accepted" | "declined";
export type ReceiptStatus = "draft" | "issued";
export type DeliveryNoteStatus = "draft" | "sent" | "delivered";
export type DocumentStatus = InvoiceStatus | EstimateStatus | ReceiptStatus | DeliveryNoteStatus;

export type PaymentMethod =
  | "cash"
  | "card"
  | "bank-transfer"
  | "check"
  | "paypal"
  | "stripe"
  | "other";

export type Payment = {
  id: string;
  date: string;         // ISO yyyy-mm-dd
  amount: number;
  method: PaymentMethod;
  note: string;
};

export type DiscountMode = "percent" | "fixed";
export type TaxMode = "percent" | "fixed";

export type Business = {
  name: string;
  email: string;
  phone: string;
  address: string;
  website: string;
  logoDataUrl?: string;
};

export type InvoicePrefs = {
  numberPrefix: string;
  nextNumber: number;
  numberPadding: number;
  defaultTerms: string;
  defaultTaxLabel: string;
  defaultTaxPercent: number;
  defaultCurrencyCode: string;
  defaultDueDays: number;

  // Estimate-specific numbering and defaults. Optional so legacy prefs
  // records load without migration.
  estimateNumberPrefix?: string;
  estimateNextNumber?: number;
  estimateNumberPadding?: number;
  estimateDefaultValidDays?: number;
  estimateDefaultTerms?: string;
};

export type Client = {
  id: string;
  name: string;
  email: string;
  phone: string;
  address: string;
  notes?: string;
};

export type SavedItem = {
  id: string;
  description: string;
  rate: number;
};

export type Invoice = {
  id: string;
  kind?: DocumentKind;         // omitted on legacy records = "invoice"
  number: string;
  status: DocumentStatus;
  createdAt: string;
  updatedAt: string;
  issueDate: string;
  dueDate: string;              // for estimates, used as "valid until"
  poNumber?: string;

  business: Business;
  billTo: Party;
  shipTo?: Party;

  items: LineItem[];

  currency: Currency;

  taxLabel: string;
  taxMode: TaxMode;
  taxValue: number;

  discountLabel: string;
  discountMode: DiscountMode;
  discountValue: number;

  shipping: number;

  notes: string;
  terms: string;

  // Legacy single-field; new code reads sum of `payments` and falls
  // back to amountPaid when payments is absent.
  amountPaid: number;
  payments?: Payment[];

  // The saved client this document was billed to, when picked from or
  // saved to the client list. Attribution (client cards, reports) uses
  // it first so it survives renames; legacy records without it fall
  // back to matching bill-to email, then name.
  clientId?: string;

  // Set on invoices generated by a recurring schedule.
  recurringId?: string;

  // Number of the invoice a receipt or delivery note was created from.
  sourceNumber?: string;

  // Which business profile owns this document. Documents without it
  // (created before multi-business support) show under the active one.
  businessId?: string;
};

// One business you invoice as. The ACTIVE profile's business/prefs live
// in the original single-business storage keys (so existing code keeps
// reading loadBusiness()/loadPrefs()); the others are parked here and
// swapped in by switchBusiness().
export type BusinessProfile = {
  id: string;
  business: Business;
  prefs: InvoicePrefs;
  counter: number;          // last invoice number issued
  estimateCounter: number;  // last estimate number issued
};

export type RecurringFrequency = "weekly" | "monthly" | "quarterly" | "yearly";

// Repeats an existing invoice ("source"). Each run copies the source's
// CURRENT content, so editing the source updates future invoices.
// Occurrence n falls on startDate + n periods (computed from the anchor,
// not chained, so month-end dates don't drift: Jan 31 → Feb 28 → Mar 31).
export type RecurringSchedule = {
  id: string;
  sourceInvoiceId: string;
  frequency: RecurringFrequency;
  startDate: string;        // issue date of the first generated invoice
  endDate?: string;         // inclusive; absent = no end
  runCount: number;         // occurrences generated so far
  active: boolean;          // false = paused or finished
  createdAt: string;
  lastRunDate?: string;
  problem?: "source-missing";
};

export type Totals = {
  subtotal: number;
  discount: number;
  tax: number;
  shipping: number;
  total: number;
  balanceDue: number;
};
